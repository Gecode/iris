//! Prints a [`View`] as a C++ header of `constexpr` handles, laid out as
//! clang-format lays them out in the style of `cpp/.clang-format`.
//!
//! The handles live in a namespace named after the spec's file, so that
//! `jobshop.iris` gives `jobshop::machine`. Identifiers are lower snake case,
//! as clang-tidy's `lower_case` wants them, and avoid only what a header must:
//! keywords, macros, and the namespaces `iris` and `std`, which a later
//! declaration names.
//!
//! A declaration is `inline constexpr TYPE identifier{"entry"};`. Identifiers
//! and handle types have a bounded width, so clang-format gives it one of four
//! layouts, depending on where the entry's literal fits. A literal too wide for
//! every layout would make clang-format split it, so that declaration stays on
//! one line between `// clang-format off` and `// clang-format on`.
use std::path::Path;

use super::names::{Identifiers, Role};
use super::{CONTINUATION, LINE_WIDTH, quoted};
use crate::view::{Access, Handle, Leaf, View};

const HEADER: &str =
    "// Typed handles of a reader spec, generated by `iris gen --lang cpp`.\n#pragma once\n";

pub(crate) fn render(view: &View, origin: &str) -> String {
    let mut text = String::from(HEADER);
    if view.handles.is_empty() {
        return text;
    }
    let handle_types: Vec<String> = view.handles.iter().map(handle_type).collect();
    text.push_str("\n#include <iris/handle.hpp>\n");
    let standard = standard_headers(&view.handles);
    if !standard.is_empty() {
        text.push('\n');
        for header in standard {
            text.push_str(&format!("#include <{header}>\n"));
        }
    }
    let namespace = namespace(origin);
    text.push_str(&format!("\nnamespace {namespace} {{\n\n"));
    let mut identifiers = Identifiers::for_handles();
    for (handle, handle_type) in view.handles.iter().zip(&handle_types) {
        let identifier = identifiers.named(Role::Value, &handle.entry);
        text.push_str(&declaration(handle_type, &identifier, &handle.entry));
    }
    text.push_str(&format!("\n}} // namespace {namespace}\n"));
    text
}

/// The namespace of a spec read from `origin`: its file name without the
/// extension, as an identifier.
fn namespace(origin: &str) -> String {
    // A Windows path separates with `\`, which `Path` sees only on Windows.
    let file = origin.rsplit(['/', '\\']).next().unwrap_or(origin);
    let stem = Path::new(file)
        .file_stem()
        .map_or(file.into(), |stem| stem.to_string_lossy());
    Identifiers::for_handles().fresh(&stem, "spec")
}

/// The standard headers that the handle types need, in clang-format's order.
fn standard_headers(handles: &[Handle]) -> Vec<&'static str> {
    let has = |leaf: Leaf| {
        handles
            .iter()
            .any(|handle| matches!(handle.access, Access::Typed { value, .. } if value == leaf))
    };
    let mut headers = Vec::new();
    if has(Leaf::Int) {
        headers.push("cstdint");
    }
    if has(Leaf::Str) {
        headers.push("string");
    }
    headers
}

/// The type of `handle`, such as `iris::Field<std::int64_t, 2>`. Templates
/// take any depth, so every depth has a typed handle.
fn handle_type(handle: &Handle) -> String {
    let Access::Typed {
        value,
        depth,
        optional,
    } = handle.access
    else {
        return "iris::DynField".into();
    };
    let value = match value {
        Leaf::Int => "std::int64_t",
        Leaf::Float => "double",
        Leaf::Str => "std::string",
        Leaf::Num => "iris::Number",
    };
    match (depth, optional) {
        (0, false) => format!("iris::Field<{value}>"),
        (_, false) => format!("iris::Field<{value}, {depth}>"),
        (_, true) => format!("iris::Field<{value}, {depth}, iris::Presence::Maybe>"),
    }
}

/// The declaration of a handle, in the layout with the fewest lines whose
/// literal fits, which is the one clang-format chooses.
fn declaration(handle_type: &str, identifier: &str, entry: &str) -> String {
    let head = format!("inline constexpr {handle_type}");
    let literal = quoted(entry);
    let one_line = format!("{head} {identifier}{{{literal}}};");
    let closed = format!("{literal}}};");
    let opened = format!("{head} {identifier}{{");
    let indent = " ".repeat(CONTINUATION);
    if one_line.len() <= LINE_WIDTH {
        return format!("{one_line}\n");
    }
    if opened.len() <= LINE_WIDTH {
        // clang-format breaks after the brace rather than before the identifier.
        if CONTINUATION + closed.len() <= LINE_WIDTH {
            return format!("{opened}\n{indent}{closed}\n");
        }
    } else if CONTINUATION + identifier.len() + 1 + closed.len() <= LINE_WIDTH {
        return format!("{head}\n{indent}{identifier}{{{closed}\n");
    } else if 2 * CONTINUATION + closed.len() <= LINE_WIDTH {
        return format!("{head}\n{indent}{identifier}{{\n{indent}{indent}{closed}\n");
    }
    format!("// clang-format off\n{one_line}\n// clang-format on\n")
}
