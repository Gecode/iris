//! Prints a [`View`] as a Java class of handle constants, laid out as
//! google-java-format lays them out.
//!
//! The class is named after the spec's file, so that `jobshop.iris` gives
//! `Jobshop.machine`, and has no package, which the file that keeps it adds.
//! Identifiers are lower camel case, as for the handles of a builder, and are
//! the ones that the annotation processor of `java/iris-processor` gives.
//!
//! A declaration is `public static final TYPE identifier = FACTORY(ARGUMENTS);`,
//! with `.optional()` after the call for an entry that may be absent. The
//! factory is `int0` to `int3` and its kin, or `intN("entry", depth)` and its
//! kin for a deeper entry, which reads a `Value` as the Java builder's
//! handles do. A literal too wide for its line stays whole, as
//! google-java-format leaves it.
//!
//! The types of `java.lang` are qualified, as in `IntField<java.lang.Long>`,
//! so that a class of the same simple name in the package that keeps the view
//! cannot take their place. The other types are imported, which a class of the
//! package cannot override either; google-java-format would remove an import
//! from `java.lang`.
use super::names::{Identifiers, Role, view_class};
use super::{CONTINUATION, LINE_WIDTH, MEMBER_COLUMN, quoted};
use crate::view::{Access, Handle, Leaf, View};

/// The deepest entry with a factory for its view type; deeper ones read a
/// `Value`.
const DEEPEST_VIEW_TYPE: usize = 3;

/// The package of the types that a view qualifies.
const JAVA_LANG: &str = "java.lang.";

const HEADER: &str = "// Typed handles of a reader spec, generated by `iris gen --lang java`.\n";

pub(crate) fn render(view: &View, origin: &str) -> String {
    let class = view_class(origin);
    let declarations: Vec<Declaration> = view.handles.iter().map(Declaration::new).collect();
    let mut text = String::from(HEADER);
    if !declarations.is_empty() {
        text.push_str("\nimport static dev.gecode.iris.build.Iris.*;\n\n");
        for import in imports(&declarations) {
            text.push_str(&format!("import {import};\n"));
        }
    }
    text.push_str(&format!("\npublic final class {class} {{\n"));
    let mut identifiers = Identifiers::for_handles();
    for (handle, declaration) in view.handles.iter().zip(&declarations) {
        let identifier = identifiers.named(Role::Value, &handle.entry);
        for line in declaration.lines(&identifier, &handle.entry) {
            text.push_str(&line);
            text.push('\n');
        }
    }
    if !declarations.is_empty() {
        text.push('\n');
    }
    text.push_str(&format!("  private {class}() {{}}\n}}\n"));
    text
}

/// The declaration of one handle, without its identifier and entry.
struct Declaration {
    /// The handle's class, such as `IntField`.
    class: &'static str,
    /// The data view type, such as `List<long[]>`, with `@Nullable` for an
    /// optional entry.
    view_type: String,
    /// The factory, such as `int2`.
    factory: String,
    /// The depth argument of an `N` factory.
    depth: Option<usize>,
    optional: bool,
    /// The imports that the declaration needs, besides the static one.
    imports: Vec<&'static str>,
}

impl Declaration {
    fn new(handle: &Handle) -> Self {
        let Access::Typed {
            value,
            depth,
            optional,
        } = handle.access
        else {
            return Self {
                class: "DynField",
                view_type: String::new(),
                factory: "dynamic".into(),
                depth: None,
                optional: false,
                imports: vec!["dev.gecode.iris.build.DynField"],
            };
        };
        let (class, prefix) = match value {
            Leaf::Int => ("IntField", "int"),
            Leaf::Float => ("FloatField", "float"),
            Leaf::Num => ("NumField", "num"),
            Leaf::Str => ("StringField", "string"),
        };
        let mut imports = vec![match value {
            Leaf::Int => "dev.gecode.iris.build.IntField",
            Leaf::Float => "dev.gecode.iris.build.FloatField",
            Leaf::Num => "dev.gecode.iris.build.NumField",
            Leaf::Str => "dev.gecode.iris.build.StringField",
        }];
        let (view_type, factory, depth_argument) = if depth > DEEPEST_VIEW_TYPE {
            imports.push("dev.gecode.iris.Value");
            (
                nullable("Value", optional),
                format!("{prefix}N"),
                Some(depth),
            )
        } else {
            let view_type = view_type(value, depth, optional);
            if view_type.contains("List<") {
                imports.push("java.util.List");
            }
            (view_type, format!("{prefix}{depth}"), None)
        };
        if optional {
            imports.push("org.jspecify.annotations.Nullable");
        }
        Self {
            class,
            view_type,
            factory,
            depth: depth_argument,
            optional,
            imports,
        }
    }

    fn handle_type(&self) -> String {
        if self.view_type.is_empty() {
            self.class.to_owned()
        } else {
            format!("{}<{}>", self.class, self.view_type)
        }
    }

    /// The declaration's lines, in the layout that google-java-format gives
    /// it: on one line, broken after `=`, then with the call and
    /// `.optional()` apart, then with each argument on a line of its own.
    fn lines(&self, identifier: &str, entry: &str) -> Vec<String> {
        let head = format!("public static final {} {identifier} =", self.handle_type());
        let mut arguments = vec![quoted(entry)];
        arguments.extend(self.depth.map(|depth| depth.to_string()));
        let call = format!("{}({})", self.factory, arguments.join(", "));
        let tail = if self.optional { ".optional()" } else { "" };
        let member = " ".repeat(MEMBER_COLUMN);
        let one_line = format!("{member}{head} {call}{tail};");
        if one_line.len() <= LINE_WIDTH {
            return vec![one_line];
        }
        let value_column = MEMBER_COLUMN + CONTINUATION;
        let value = " ".repeat(value_column);
        let mut lines = vec![format!("{member}{head}")];
        if value_column + call.len() + tail.len() + ";".len() <= LINE_WIDTH {
            lines.push(format!("{value}{call}{tail};"));
            return lines;
        }
        if !self.optional {
            // The arguments go one level in, together if they fit.
            let inner_column = value_column + CONTINUATION;
            lines.extend(broken_call(
                &self.factory,
                &arguments,
                ");",
                value_column,
                inner_column,
            ));
            return lines;
        }
        let chain = " ".repeat(value_column + CONTINUATION);
        // A name no longer than the indent before a chain's arguments gains
        // nothing from a break after it, so google-java-format keeps a single
        // argument beside it.
        let short = arguments.len() == 1 && self.factory.len() <= CONTINUATION;
        if short || value_column + call.len() <= LINE_WIDTH {
            lines.push(format!("{value}{call}"));
        } else {
            // In a chain, the arguments go two levels in.
            let inner_column = value_column + 2 * CONTINUATION;
            lines.extend(broken_call(
                &self.factory,
                &arguments,
                ")",
                value_column,
                inner_column,
            ));
        }
        lines.push(format!("{chain}.optional();"));
        lines
    }
}

/// `factory(` at `column` and then its arguments at `inner_column`, on one
/// line if they fit and otherwise one on each line, followed by `close`.
fn broken_call(
    factory: &str,
    arguments: &[String],
    close: &str,
    column: usize,
    inner_column: usize,
) -> Vec<String> {
    let inner = " ".repeat(inner_column);
    let mut lines = vec![format!("{}{factory}(", " ".repeat(column))];
    let together = format!("{}{close}", arguments.join(", "));
    if inner_column + together.len() <= LINE_WIDTH {
        lines.push(format!("{inner}{together}"));
        return lines;
    }
    for (index, argument) in arguments.iter().enumerate() {
        let end = if index + 1 == arguments.len() {
            close
        } else {
            ","
        };
        lines.push(format!("{inner}{argument}{end}"));
    }
    lines
}

/// The type that `data.get` returns for `value` at `depth`, as the factories
/// type it: `Long`, `long[]` and a `List` for each further level for
/// integers, and `List<String>` and `List<Number>` at depth 1, with the types
/// of `java.lang` qualified.
fn view_type(value: Leaf, depth: usize, optional: bool) -> String {
    let (single, row) = match value {
        Leaf::Int => ("java.lang.Long", "long[]"),
        Leaf::Float => ("java.lang.Double", "double[]"),
        Leaf::Num => ("java.lang.Number", "List<java.lang.Number>"),
        Leaf::Str => ("java.lang.String", "List<java.lang.String>"),
    };
    match depth {
        0 => nullable(single, optional),
        _ => {
            let lists = depth - 1;
            let nested = format!("{}{row}{}", "List<".repeat(lists), ">".repeat(lists));
            nullable(&nested, optional)
        }
    }
}

/// `view_type` with JSpecify's `@Nullable` where it applies: before a class's
/// simple name, after its package, and between the element type and `[]` of
/// an array.
fn nullable(view_type: &str, optional: bool) -> String {
    if !optional {
        return view_type.to_owned();
    }
    if let Some(element) = view_type.strip_suffix("[]") {
        return format!("{element} @Nullable []");
    }
    match view_type.strip_prefix(JAVA_LANG) {
        Some(simple) => format!("{JAVA_LANG}@Nullable {simple}"),
        None => format!("@Nullable {view_type}"),
    }
}

/// The imports of `declarations`, sorted as google-java-format sorts them.
fn imports(declarations: &[Declaration]) -> Vec<&'static str> {
    let mut imports: Vec<&'static str> = declarations
        .iter()
        .flat_map(|declaration| declaration.imports.iter().copied())
        .collect();
    imports.sort_unstable();
    imports.dedup();
    imports
}
