//! Prints a [`View`] as a Kotlin object of handle properties, laid out as
//! ktfmt's kotlinlang style lays them out.
//!
//! The object is named after the spec's file, so that `jobshop.iris` gives
//! `Jobshop.machine`, and the file has no package, which the file that keeps
//! it adds. Identifiers are lower camel case, as for the handles of a builder.
//!
//! A property is `public val identifier: TYPE = FACTORY(ARGUMENTS)`, with
//! `.optional()` after the call for an entry that may be absent. The factory
//! is `int0` to `int3` and its kin, or `intN("entry", depth)` and its kin for a
//! deeper entry, which reads a `Value` as the builder's handles do. A literal
//! too wide for its line stays whole, as ktfmt leaves it.
//!
//! The view imports every type it names, those of the standard library too,
//! since a class of the same simple name in the package that keeps the view
//! would take the place of a default import, but not of an explicit one.
use super::names::{Identifiers, Role, view_object};
use super::{LINE_WIDTH, TAB, quoted};
use crate::view::{Access, Handle, Leaf, View};

/// The deepest entry with a factory for its view type; deeper ones read a
/// `Value`.
const DEEPEST_VIEW_TYPE: usize = 3;

/// The column of a property of the object.
const PROPERTY_COLUMN: usize = TAB;

const HEADER: &str = "// Typed handles of a reader spec, generated by `iris gen --lang kotlin`.\n";

pub(crate) fn render(view: &View, origin: &str) -> String {
    let object = view_object(origin);
    let properties: Vec<Property> = view.handles.iter().map(Property::new).collect();
    let mut text = String::from(HEADER);
    if properties.is_empty() {
        text.push_str(&format!("\npublic object {object}\n"));
        return text;
    }
    text.push('\n');
    for import in imports(&properties) {
        text.push_str(&format!("import {import}\n"));
    }
    text.push_str(&format!("\npublic object {object} {{\n"));
    let mut identifiers = Identifiers::for_handles();
    for (handle, property) in view.handles.iter().zip(&properties) {
        let identifier = identifiers.named(Role::Value, &handle.entry);
        for line in property.lines(&identifier, &handle.entry) {
            text.push_str(&line);
            text.push('\n');
        }
    }
    text.push_str("}\n");
    text
}

/// The property of one handle, without its identifier and entry.
struct Property {
    /// The handle's class, such as `IntField`.
    class: &'static str,
    /// The data view type, such as `List<LongArray>`, with `?` for an
    /// optional entry.
    view_type: String,
    /// The factory, such as `int2`.
    factory: String,
    /// The depth argument of an `N` factory.
    depth: Option<usize>,
    optional: bool,
}

impl Property {
    fn new(handle: &Handle) -> Self {
        let Access::Typed {
            value,
            depth,
            optional,
        } = handle.access
        else {
            return Self {
                class: "DynField",
                view_type: String::new(),
                factory: "dynamic".into(),
                depth: None,
                optional: false,
            };
        };
        let (class, prefix) = match value {
            Leaf::Int => ("IntField", "int"),
            Leaf::Float => ("FloatField", "float"),
            Leaf::Num => ("NumField", "num"),
            Leaf::Str => ("StringField", "string"),
        };
        let nullable = if optional { "?" } else { "" };
        let (view_type, factory, depth_argument) = if depth > DEEPEST_VIEW_TYPE {
            (
                format!("Value{nullable}"),
                format!("{prefix}N"),
                Some(depth),
            )
        } else {
            (
                format!("{}{nullable}", view_type(value, depth)),
                format!("{prefix}{depth}"),
                None,
            )
        };
        Self {
            class,
            view_type,
            factory,
            depth: depth_argument,
            optional,
        }
    }

    fn handle_type(&self) -> String {
        if self.view_type.is_empty() {
            self.class.to_owned()
        } else {
            format!("{}<{}>", self.class, self.view_type)
        }
    }

    /// The imports that the property needs.
    fn imports(&self) -> Vec<String> {
        let mut imports = vec![
            format!("dev.gecode.iris.build.{}", self.class),
            format!("dev.gecode.iris.kotlin.build.{}", self.factory),
        ];
        imports.extend(
            type_names(&self.view_type)
                .filter_map(qualified)
                .map(str::to_owned),
        );
        imports
    }

    /// The property's lines, in the layout that ktfmt gives it: on one line,
    /// broken after `=`, then with the call and `.optional()` apart, then with
    /// each argument on a line of its own.
    fn lines(&self, identifier: &str, entry: &str) -> Vec<String> {
        let head = format!("public val {identifier}: {} =", self.handle_type());
        let mut arguments = vec![quoted(entry)];
        arguments.extend(self.depth.map(|depth| depth.to_string()));
        let call = format!("{}({})", self.factory, arguments.join(", "));
        let tail = if self.optional { ".optional()" } else { "" };
        let property = " ".repeat(PROPERTY_COLUMN);
        let one_line = format!("{property}{head} {call}{tail}");
        if one_line.len() <= LINE_WIDTH {
            return vec![one_line];
        }
        let value_column = PROPERTY_COLUMN + TAB;
        let value = " ".repeat(value_column);
        let mut lines = vec![format!("{property}{head}")];
        if value_column + call.len() + tail.len() <= LINE_WIDTH {
            lines.push(format!("{value}{call}{tail}"));
            return lines;
        }
        if !self.optional {
            lines.extend(broken_call(
                &self.factory,
                &arguments,
                value_column,
                value_column,
            ));
            return lines;
        }
        let chain_column = value_column + TAB;
        if value_column + call.len() <= LINE_WIDTH {
            lines.push(format!("{value}{call}"));
        } else {
            // In a chain, the arguments go two levels in and the parenthesis
            // one.
            let mut call_lines = broken_call(&self.factory, &arguments, value_column, chain_column);
            let close = call_lines.len() - 1;
            for line in &mut call_lines[1..close] {
                line.insert_str(0, &" ".repeat(TAB));
            }
            lines.extend(call_lines);
        }
        lines.push(format!("{}.optional()", " ".repeat(chain_column)));
        lines
    }
}

/// `factory(` at `column`, then its arguments one level in, a single one
/// alone and several with a comma after each, then `)` at `close_column`.
fn broken_call(
    factory: &str,
    arguments: &[String],
    column: usize,
    close_column: usize,
) -> Vec<String> {
    let inner = " ".repeat(column + TAB);
    let mut lines = vec![format!("{}{factory}(", " ".repeat(column))];
    if let [argument] = arguments {
        lines.push(format!("{inner}{argument}"));
    } else {
        lines.extend(
            arguments
                .iter()
                .map(|argument| format!("{inner}{argument},")),
        );
    }
    lines.push(format!("{})", " ".repeat(close_column)));
    lines
}

/// The type that `data[handle]` gives for `value` at `depth`, as the
/// factories type it: `Long`, `LongArray` and a `List` for each further level
/// for integers, and `List<String>` and `List<Number>` at depth 1.
fn view_type(value: Leaf, depth: usize) -> String {
    let (single, row) = match value {
        Leaf::Int => ("Long", "LongArray"),
        Leaf::Float => ("Double", "DoubleArray"),
        Leaf::Num => ("Number", "List<Number>"),
        Leaf::Str => ("String", "List<String>"),
    };
    match depth {
        0 => single.to_owned(),
        _ => {
            let lists = depth - 1;
            format!("{}{row}{}", "List<".repeat(lists), ">".repeat(lists))
        }
    }
}

/// The simple names in a view type, such as `List` and `LongArray` in
/// `List<LongArray>?`.
fn type_names(view_type: &str) -> impl Iterator<Item = &str> {
    view_type
        .split(['<', '>', '?'])
        .filter(|name| !name.is_empty())
}

/// The qualified name of a type that a view type names.
fn qualified(name: &str) -> Option<&'static str> {
    Some(match name {
        "Long" => "kotlin.Long",
        "Double" => "kotlin.Double",
        "Number" => "kotlin.Number",
        "String" => "kotlin.String",
        "LongArray" => "kotlin.LongArray",
        "DoubleArray" => "kotlin.DoubleArray",
        "List" => "kotlin.collections.List",
        "Value" => "dev.gecode.iris.Value",
        _ => return None,
    })
}

/// The imports of `properties`, sorted as ktfmt sorts them.
fn imports(properties: &[Property]) -> Vec<String> {
    let mut imports: Vec<String> = properties.iter().flat_map(Property::imports).collect();
    imports.sort_unstable();
    imports.dedup();
    imports
}
