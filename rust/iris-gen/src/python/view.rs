//! Prints a [`View`] as a Python module of handles declared with
//! `ib.declared`, laid out as `ruff format` lays them out.
//!
//! Identifiers follow the builder program's rules, without a leading
//! underscore, which would make a handle private to the module.
//!
//! A declaration is one call with two arguments, the entry's name and the
//! handle type, so it has only three layouts. Every handle type up to depth
//! [`DEEPEST_TYPED`] fits on a line of its own, so ruff never has to break one.
use super::names::Identifiers;
use super::{LINE_WIDTH, TAB, quoted};
use crate::view::{Access, Handle, Leaf, View};

/// The deepest entry with a typed handle. The widest handle type one level
/// deeper, `ib.NumField[list[...[int | float]...] | None]`, no longer fits on a
/// line of its own after an indentation and before a comma.
const DEEPEST_TYPED: usize = 8;

const HEADER: &str =
    "\"\"\"Typed handles of a reader spec, generated by `iris gen --lang python`.\"\"\"\n";

const IMPORT: &str = "import gecode_iris.build as ib\n";

pub(crate) fn render(view: &View) -> String {
    let mut text = String::from(HEADER);
    if view.handles.is_empty() {
        return text;
    }
    text.push('\n');
    text.push_str(IMPORT);
    text.push('\n');
    let mut identifiers = Identifiers::default();
    for handle in &view.handles {
        let identifier = identifiers.fresh(handle.entry.trim_start_matches('_'), "name");
        text.push_str(&declaration(&identifier, handle));
    }
    text
}

/// The handle type that `ib.declared` takes, such as `ib.IntField[list[int]]`.
fn handle_type(handle: &Handle) -> String {
    let Access::Typed {
        value,
        depth,
        optional,
    } = handle.access
    else {
        return "ib.DynField".into();
    };
    if depth > DEEPEST_TYPED {
        return "ib.DynField".into();
    }
    let (class, leaf) = match value {
        Leaf::Int => ("IntField", "int"),
        Leaf::Float => ("FloatField", "float"),
        Leaf::Str => ("StrField", "str"),
        Leaf::Num => ("NumField", "int | float"),
    };
    let lists = "list[".repeat(depth);
    let closes = "]".repeat(depth);
    let absent = if optional { " | None" } else { "" };
    format!("ib.{class}[{lists}{leaf}{closes}{absent}]")
}

fn declaration(identifier: &str, handle: &Handle) -> String {
    let head = format!("{identifier} = ib.declared(");
    let (name, kind) = (quoted(&handle.entry), handle_type(handle));
    let arguments = format!("{name}, {kind}");
    if head.len() + arguments.len() + ")".len() <= LINE_WIDTH {
        format!("{head}{arguments})\n")
    } else if TAB + arguments.len() <= LINE_WIDTH {
        format!("{head}\n    {arguments}\n)\n")
    } else {
        format!("{head}\n    {name},\n    {kind},\n)\n")
    }
}
