//! Prints a [`View`] as a Rust module of `const` handles, through a
//! [`RustView`] that the `iris!` macro of `gecode-iris` also uses.
//!
//! Identifiers have a bounded width, so a declaration has only three layouts,
//! which depend on its length as `rustfmt` decides.
//!
//! The text has to work as a module file and through `include!`, which takes no
//! inner attributes or inner doc comments. So the header is a plain comment and
//! every declaration carries its own attribute.
use std::collections::BTreeSet;

use super::names::{Identifiers, Role};
use super::{LINE_WIDTH, TAB, quoted};
use crate::view::{Access, Handle, Leaf, View};

/// The deepest entry with a depth type. `gecode_iris::build` stops at `D8`.
const DEEPEST_TYPED: usize = 8;

/// The longest `use` line `rustfmt` keeps whole. It stops two columns short of
/// the line width, as `imports_are_laid_out_as_rustfmt_does` confirms.
const WIDEST_IMPORT: usize = LINE_WIDTH - 2;

const HEADER: &str = "// Typed handles of a reader spec, generated by `iris gen --lang rust`.\n";

/// A handle may go unused, and it is named like its entry.
const ALLOW: &str = "#[allow(dead_code, non_upper_case_globals)]\n";

/// The handles of a view as Rust declarations: what `iris gen --lang rust`
/// prints, as data. The `iris!` macro of `gecode-iris` declares the same
/// handles as fields beside a `spec` field.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct RustView {
    /// The names of `gecode_iris::build` that the handle types use, sorted.
    pub imports: Vec<String>,
    pub handles: Vec<RustHandle>,
}

/// One handle as a Rust declaration.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RustHandle {
    /// A snake-case identifier that no other handle has, and never a keyword
    /// or `spec`.
    pub identifier: String,
    /// The handle's type, such as `Field<Int, D2, Maybe>`, naming only `imports`.
    pub handle_type: String,
    /// The entry's name in the data.
    pub entry: String,
}

impl RustView {
    pub(crate) fn new(view: &View) -> Self {
        let mut identifiers = Identifiers::for_handles();
        // Every declaration calls `Field::declared`, and a handle type comes with it.
        let mut imports = BTreeSet::from(["Field".to_owned()]);
        let mut handles = Vec::with_capacity(view.handles.len());
        for handle in &view.handles {
            handles.push(RustHandle {
                identifier: identifiers.named(Role::Handle, &handle.entry),
                handle_type: handle_type(handle, &mut imports),
                entry: handle.entry.clone(),
            });
        }
        if handles.is_empty() {
            imports.clear();
        }
        Self {
            imports: imports.into_iter().collect(),
            handles,
        }
    }
}

pub(crate) fn render(view: &RustView) -> String {
    let mut text = String::from(HEADER);
    if view.handles.is_empty() {
        return text;
    }
    text.push('\n');
    text.push_str(&import(&view.imports));
    text.push('\n');
    for handle in &view.handles {
        text.push_str(ALLOW);
        text.push_str(&declaration(handle));
    }
    text
}

/// The type of `handle`, adding what it names to `imports`.
fn handle_type(handle: &Handle, imports: &mut BTreeSet<String>) -> String {
    let Access::Typed {
        value,
        depth,
        optional,
    } = handle.access
    else {
        imports.insert("DynField".into());
        return "DynField".into();
    };
    if depth > DEEPEST_TYPED {
        imports.insert("DynField".into());
        return "DynField".into();
    }
    let value = match value {
        Leaf::Int => "Int",
        Leaf::Float => "Float",
        Leaf::Str => "Str",
        Leaf::Num => "Num",
    };
    imports.insert(value.into());
    let depth_type = format!("D{depth}");
    let arguments = match (depth, optional) {
        (0, false) => value.to_owned(),
        (_, false) => format!("{value}, {depth_type}"),
        (_, true) => format!("{value}, {depth_type}, Maybe"),
    };
    if depth > 0 || optional {
        imports.insert(depth_type);
    }
    if optional {
        imports.insert("Maybe".into());
    }
    format!("Field<{arguments}>")
}

fn import(names: &[String]) -> String {
    let list = names.join(", ");
    let line = format!("use gecode_iris::build::{{{list}}};\n");
    if line.len() - 1 <= WIDEST_IMPORT {
        line
    } else {
        format!("use gecode_iris::build::{{\n    {list},\n}};\n")
    }
}

fn declaration(handle: &RustHandle) -> String {
    let head = format!("pub const {}: {} =", handle.identifier, handle.handle_type);
    let name = quoted(&handle.entry);
    let call = format!("Field::declared({name});");
    if head.len() + " ".len() + call.len() <= LINE_WIDTH {
        format!("{head} {call}\n")
    } else if TAB + call.len() <= LINE_WIDTH {
        format!("{head}\n    {call}\n")
    } else {
        format!("{head} Field::declared(\n    {name},\n);\n")
    }
}
