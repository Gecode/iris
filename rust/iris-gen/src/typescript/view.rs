//! Prints a [`View`] as a TypeScript module of handle constants, laid out as
//! oxfmt lays them out.
//!
//! A handle is a plain object with the shape of the `Handle` interface of
//! `gecode-iris`, which `data.get` accepts, declared with the handle type
//! that a builder's handle of the same entry has, such as
//! `Handle<"int", 2, "required">`. The module imports only that type, so it
//! loads nothing when it runs and serves every entry point of the package.
//!
//! Identifiers follow the builder program's rules, but avoid only the words
//! that JavaScript or oxlint refuse, `Handle`, the one name the module binds
//! itself, and `then`, which no module should export.
//!
//! oxfmt keeps an object on several lines when its first property starts a
//! line, so every declaration has one layout: its head, which identifiers of
//! at most 24 characters keep within a line, and one property on each line.
use super::names::{Identifiers, Role};
use super::quoted;
use crate::view::{Access, Handle, Leaf, View};

/// The deepest depth that `HandleDepth` names. A deeper entry's handle has
/// the open depth `null`, as a builder's handle has.
const DEEPEST_DEPTH: usize = 8;

const HEADER: &str =
    "// Typed handles of a reader spec, generated by `iris gen --lang typescript`.\n";

const IMPORT: &str = "\nimport type { Handle } from \"gecode-iris\";\n";

pub(crate) fn render(view: &View) -> String {
    let mut text = String::from(HEADER);
    if view.handles.is_empty() {
        // A file without an import or export is a script, which no module can
        // import, and oxlint refuses an empty file and `export {}`, so the
        // module passes on the type that its handles would have.
        text.push_str("\nexport type { Handle } from \"gecode-iris\";\n");
        return text;
    }
    text.push_str(IMPORT);
    let mut identifiers = Identifiers::for_handles();
    for handle in &view.handles {
        let identifier = identifiers.named(Role::Value, &handle.entry);
        text.push('\n');
        text.push_str(&declaration(&identifier, handle));
    }
    text
}

/// What a handle promises, as the type arguments of `Handle` spell it.
struct Promise {
    value_type: &'static str,
    /// A depth, or `null`.
    depth: String,
    presence: &'static str,
}

impl Promise {
    /// The promise of a builder's handle for an entry with `access`. A
    /// dynamic one is the builder's `DynField`.
    fn new(access: Access) -> Self {
        let Access::Typed {
            value,
            depth,
            optional,
        } = access
        else {
            return Self {
                value_type: "dyn",
                depth: "null".into(),
                presence: "maybe",
            };
        };
        let value_type = match value {
            Leaf::Int => "int",
            Leaf::Float => "float",
            Leaf::Str => "string",
            Leaf::Num => "num",
        };
        Self {
            value_type,
            depth: if depth > DEEPEST_DEPTH {
                "null".into()
            } else {
                depth.to_string()
            },
            presence: if optional { "maybe" } else { "required" },
        }
    }
}

fn declaration(identifier: &str, handle: &Handle) -> String {
    let Promise {
        value_type,
        depth,
        presence,
    } = Promise::new(handle.access);
    let name = quoted(&handle.entry);
    format!(
        "export const {identifier}: Handle<\"{value_type}\", {depth}, \"{presence}\"> = {{\n  \
         name: {name},\n  \
         valueType: \"{value_type}\",\n  \
         depth: {depth},\n  \
         presence: \"{presence}\",\n\
         }};\n"
    )
}
