//! The C++ text of a view. Which handle each entry gets is in `rust_view.rs`;
//! `gecode-iris`'s `cpp_views` test compiles the output, reads with it and runs
//! clang-format on it.
use gecode_iris_gen::{Language, view_code};
use gecode_iris_sema::analyze;
use gecode_iris_syntax::{LanguageVersion, parse};

fn code_of(source: &str, origin: &str) -> String {
    let parsed = parse(source.as_bytes(), origin, LanguageVersion::V0_1).unwrap();
    view_code(&parsed, &analyze(&parsed), Language::Cpp).expect("the spec is accepted")
}

fn code(source: &str) -> String {
    code_of(source, "test.iris")
}

const HEADER: &str =
    "// Typed handles of a reader spec, generated by `iris gen --lang cpp`.\n#pragma once\n";

#[test]
fn cpp_has_a_view_printer() {
    assert!(Language::Cpp.has_view());
}

#[test]
fn a_spec_without_entries_prints_only_the_header() {
    assert_eq!(code("skip line\n"), HEADER);
}

#[test]
fn each_handle_type_gives_its_view() {
    let source = "n:int a[1]:float if n {s:word m[1][1]:num} x:int x:word";
    let expected = format!(
        "{HEADER}
#include <iris/handle.hpp>

#include <cstdint>
#include <string>

namespace test {{

inline constexpr iris::Field<std::int64_t> n{{\"n\"}};
inline constexpr iris::Field<double, 1> a{{\"a\"}};
inline constexpr iris::Field<std::string, 0, iris::Presence::Maybe> s{{\"s\"}};
inline constexpr iris::Field<iris::Number, 2, iris::Presence::Maybe> m{{\"m\"}};
inline constexpr iris::DynField x{{\"x\"}};

}} // namespace test
"
    );
    assert_eq!(code(source), expected);
}

#[test]
fn only_the_value_types_in_use_include_their_headers() {
    let floats = code("a:float b[1]:num");
    assert!(floats.contains("#include <iris/handle.hpp>\n\nnamespace test {\n"));
    let dynamic = code("x:int x:word");
    assert!(dynamic.contains("#include <iris/handle.hpp>\n\nnamespace test {\n"));
    assert!(code("s:word").contains("#include <iris/handle.hpp>\n\n#include <string>\n\n"));
}

#[test]
fn every_depth_has_a_typed_handle() {
    let spec = format!("{}v:int{}", "repeat 1 {".repeat(9), "}".repeat(9));
    assert!(code(&spec).contains("inline constexpr iris::Field<std::int64_t, 9> v{\"v\"};\n"));
}

#[test]
fn the_namespace_is_named_after_the_spec_file() {
    for (origin, namespace) in [
        ("formats/jobshop/jobshop.iris", "jobshop"),
        ("C:\\specs\\dimacs-cnf.iris", "dimacs_cnf"),
        ("TspTw", "tsp_tw"),
        ("9.iris", "spec_9"),
        ("", "spec"),
        ("int.iris", "int_2"),
        ("iris.iris", "iris_2"),
        ("std.iris", "std_2"),
    ] {
        let text = code_of("n:int", origin);
        assert!(
            text.contains(&format!("\nnamespace {namespace} {{\n"))
                && text.ends_with(&format!("\n}} // namespace {namespace}\n")),
            "{origin}: {text}"
        );
    }
}

#[test]
fn identifiers_are_snake_case_and_avoid_what_a_header_reserves() {
    let name = "n".repeat(30);
    let source = format!(
        "if:int int:int iris:int std:int assert:int count:int b:int aB:int a_b:int \
         _c:int {name}a:int {name}b:int"
    );
    let text = code(&source);
    for (identifier, entry) in [
        ("if_2", "if"),
        ("int_2", "int"),
        ("iris_2", "iris"),
        ("std_2", "std"),
        ("assert_2", "assert"),
        ("count", "count"),
        ("b", "b"),
        ("a_b", "aB"),
        ("a_b_2", "a_b"),
        ("c", "_c"),
    ] {
        let line =
            format!("inline constexpr iris::Field<std::int64_t> {identifier}{{\"{entry}\"}};\n");
        assert!(text.contains(&line), "{line}in\n{text}");
    }
    let short = "n".repeat(24);
    assert!(text.contains(&format!(" {short}{{\n    \"{name}a\"}};\n")));
    assert!(text.contains(&format!(" {short}_2{{\n    \"{name}b\"}};\n")));
}

#[test]
fn a_declaration_breaks_as_clang_format_breaks_it() {
    const MAYBE_NUM: &str = "inline constexpr iris::Field<iris::Number, 1, iris::Presence::Maybe>";

    // One line, up to the last column.
    let entry = "x".repeat(16);
    assert!(code(&format!("{entry}:int")).contains(&format!(
        "\ninline constexpr iris::Field<std::int64_t> {entry}{{\"{entry}\"}};\n"
    )));

    // A break after the brace, while the identifier fits before it.
    let entry = "y".repeat(60);
    assert!(code(&format!("{entry}:int")).contains(&format!(
        "inline constexpr iris::Field<std::int64_t> {}{{\n    \"{entry}\"}};\n",
        "y".repeat(24)
    )));

    // A break before the identifier, which does not fit on the first line.
    let entry = "z".repeat(20);
    let spec = format!("if 1 {{ {entry}[1]:num }}");
    assert!(
        code(&spec).contains(&format!("{MAYBE_NUM}\n    {entry}{{\"{entry}\"}};\n")),
        "{}",
        code(&spec)
    );

    // Breaks before the identifier and after the brace.
    let entry = "w".repeat(60);
    let spec = format!("if 1 {{ {entry}[1]:num }}");
    assert!(code(&spec).contains(&format!(
        "{MAYBE_NUM}\n    {}{{\n        \"{entry}\"}};\n",
        "w".repeat(24)
    )));
}

#[test]
fn a_literal_too_wide_for_any_layout_turns_clang_format_off() {
    let entry = "v".repeat(80);
    let text = code(&format!("{entry}:int"));
    let line = format!(
        "inline constexpr iris::Field<std::int64_t> {}{{\"{entry}\"}};",
        "v".repeat(24)
    );
    assert!(
        text.contains(&format!(
            "// clang-format off\n{line}\n// clang-format on\n"
        )),
        "{text}"
    );
}
