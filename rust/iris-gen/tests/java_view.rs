//! The Java text of a view. Which handle each entry gets is in `rust_view.rs`;
//! the `iris-views` module of `java/` compiles the output, reads with it and
//! checks it with google-java-format.
use gecode_iris_gen::{Language, view_code};
use gecode_iris_sema::analyze;
use gecode_iris_syntax::{LanguageVersion, parse};

fn code_of(source: &str, origin: &str) -> String {
    let parsed = parse(source.as_bytes(), origin, LanguageVersion::V0_1).unwrap();
    view_code(&parsed, &analyze(&parsed), Language::Java).expect("the spec is accepted")
}

fn code(source: &str) -> String {
    code_of(source, "test.iris")
}

const HEADER: &str = "// Typed handles of a reader spec, generated by `iris gen --lang java`.\n";

#[test]
fn java_has_a_view_printer() {
    assert!(Language::Java.has_view());
}

#[test]
fn a_spec_without_entries_prints_a_class_without_handles() {
    assert_eq!(
        code("skip line\n"),
        format!("{HEADER}\npublic final class Test {{\n  private Test() {{}}\n}}\n")
    );
}

#[test]
fn each_handle_type_gives_its_view() {
    let source = "n:int a[1]:float b[1][1]:int c[1][1][1]:num if n {s:word m[1][1]:num t[1]:int} \
                  x:int x:word";
    let expected = format!(
        "{HEADER}
import static dev.gecode.iris.build.Iris.*;

import dev.gecode.iris.build.DynField;
import dev.gecode.iris.build.FloatField;
import dev.gecode.iris.build.IntField;
import dev.gecode.iris.build.NumField;
import dev.gecode.iris.build.StringField;
import java.util.List;
import org.jspecify.annotations.Nullable;

public final class Test {{
  public static final IntField<java.lang.Long> n = int0(\"n\");
  public static final FloatField<double[]> a = float1(\"a\");
  public static final IntField<List<long[]>> b = int2(\"b\");
  public static final NumField<List<List<List<java.lang.Number>>>> c = num3(\"c\");
  public static final StringField<java.lang.@Nullable String> s = string0(\"s\").optional();
  public static final NumField<@Nullable List<List<java.lang.Number>>> m = num2(\"m\").optional();
  public static final IntField<long @Nullable []> t = int1(\"t\").optional();
  public static final DynField x = dynamic(\"x\");

  private Test() {{}}
}}
"
    );
    assert_eq!(code(source), expected);
}

#[test]
fn only_the_types_in_use_are_imported() {
    let text = code("a:float");
    assert!(text.contains(
        "import static dev.gecode.iris.build.Iris.*;\n\nimport dev.gecode.iris.build.FloatField;\n\npublic"
    ));
    assert!(code("s[1]:word").contains("StringField;\nimport java.util.List;\n\npublic"));
}

#[test]
fn a_deeper_entry_reads_a_value() {
    let spec = format!("{}v:int{}", "repeat 1 {".repeat(4), "}".repeat(4));
    let text = code(&spec);
    assert!(text.contains("import dev.gecode.iris.Value;\n"), "{text}");
    assert!(text.contains("  public static final IntField<Value> v = intN(\"v\", 4);\n"));
    let spec = format!(
        "if 1 {{ {}v:word{} }}",
        "repeat 1 {".repeat(5),
        "}".repeat(5)
    );
    assert!(code(&spec).contains(
        "  public static final StringField<@Nullable Value> v = stringN(\"v\", 5).optional();\n"
    ));
}

#[test]
fn the_class_is_named_after_the_spec_file() {
    for (origin, class) in [
        ("formats/jobshop/jobshop.iris", "Jobshop"),
        ("C:\\specs\\dimacs-cnf.iris", "DimacsCnf"),
        ("tsp_tw.iris", "TspTw"),
        ("9.iris", "Spec9"),
        ("", "Spec"),
        ("value.iris", "Value2"),
        ("int-field.iris", "IntField2"),
        ("list.iris", "List2"),
    ] {
        let text = code_of("n:int", origin);
        assert!(
            text.contains(&format!("\npublic final class {class} {{\n"))
                && text.ends_with(&format!("\n  private {class}() {{}}\n}}\n")),
            "{origin}: {text}"
        );
    }
}

#[test]
fn identifiers_are_camel_case_and_avoid_what_the_processor_reserves() {
    let name = "n".repeat(25);
    let source = format!(
        "if:int int:int var:int e1:int args:int spec:int reader:int java:int hashCode:int \
         to_string:int int0:int count:int aB:int a_b:int _c:int Field:int {name}a:int {name}b:int"
    );
    let text = code(&source);
    for (identifier, entry) in [
        ("if2", "if"),
        ("int2", "int"),
        ("var2", "var"),
        ("e1", "e1"),
        ("args", "args"),
        ("spec2", "spec"),
        ("reader2", "reader"),
        ("java2", "java"),
        ("hashCode2", "hashCode"),
        ("toString2", "to_string"),
        ("int0", "int0"),
        ("count", "count"),
        ("aB", "aB"),
        ("aB2", "a_b"),
        ("c", "_c"),
        ("field", "Field"),
    ] {
        let line = format!(
            "  public static final IntField<java.lang.Long> {identifier} = int0(\"{entry}\");\n"
        );
        assert!(text.contains(&line), "{line}in\n{text}");
    }
    let short = "n".repeat(24);
    assert!(text.contains(&format!(" {short} =\n      int0(\"{name}a\");\n")));
    assert!(text.contains(&format!(" {short}2 =\n      int0(\"{name}b\");\n")));
}

#[test]
fn a_declaration_breaks_as_google_java_format_breaks_it() {
    const OPTIONAL_STRING: &str =
        "  public static final StringField<@Nullable List<java.lang.String>>";

    // One line, up to the last column.
    let entry = "x".repeat(25);
    let short = "x".repeat(24);
    let line = format!("  public static final IntField<long[]> {short} = int1(\"{entry}\");\n");
    assert_eq!(line.len(), 101);
    assert!(code(&format!("{entry}[1]:int")).contains(&line));

    // A break after `=`.
    let entry = "y".repeat(40);
    let short = "y".repeat(24);
    assert!(code(&format!("{entry}:int")).contains(&format!(
        "  public static final IntField<java.lang.Long> {short} =\n      int0(\"{entry}\");\n"
    )));

    // The call and `.optional()` apart.
    let entry = "z".repeat(80);
    let short = "z".repeat(24);
    assert!(
        code(&format!("if 1 {{ {entry}[1]:word }}")).contains(&format!(
            "{OPTIONAL_STRING} {short} =\n      string1(\"{entry}\")\n          .optional();\n"
        ))
    );

    // The argument of the call apart as well.
    let entry = "w".repeat(90);
    let short = "w".repeat(24);
    let text = code(&format!("if 1 {{ {entry}[1]:word }}"));
    assert!(
        text.contains(&format!(
            "{OPTIONAL_STRING} {short} =\n      string1(\n              \"{entry}\")\n          .optional();\n"
        )),
        "{text}"
    );

    // Unless the factory's name is no wider than the indent.
    let entry = "v".repeat(90);
    let short = "v".repeat(24);
    assert!(code(&format!("if 1 {{ {entry}:int }}")).contains(&format!(
        "{short} =\n      int0(\"{entry}\")\n          .optional();\n"
    )));

    // Without `.optional()`, the arguments go one level in.
    let entry = "u".repeat(90);
    let short = "u".repeat(24);
    assert!(code(&format!("{entry}:int")).contains(&format!(
        "{short} =\n      int0(\n          \"{entry}\");\n"
    )));

    // And one on each line when they do not fit together.
    let entry = "t".repeat(90);
    let short = "t".repeat(24);
    let spec = format!("{}{entry}:int{}", "repeat 1 {".repeat(4), "}".repeat(4));
    assert!(code(&spec).contains(&format!(
        "{short} =\n      intN(\n          \"{entry}\",\n          4);\n"
    )));
}
