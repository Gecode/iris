#[test]
fn handle_types_name_only_what_differs_from_the_defaults() {
    let source = "n:int a[1]:float if n {s:word m[1][1]:num} x:int x:word";
    let expected = format!(
        "{HEADER}
use gecode_iris::build::{{D0, D1, D2, DynField, Field, Float, Int, Maybe, Num, Str}};

#[allow(dead_code, non_upper_case_globals)]
pub const n: Field<Int> = Field::declared(\"n\");
#[allow(dead_code, non_upper_case_globals)]
pub const a: Field<Float, D1> = Field::declared(\"a\");
#[allow(dead_code, non_upper_case_globals)]
pub const s: Field<Str, D0, Maybe> = Field::declared(\"s\");
#[allow(dead_code, non_upper_case_globals)]
pub const m: Field<Num, D2, Maybe> = Field::declared(\"m\");
#[allow(dead_code, non_upper_case_globals)]
pub const x: DynField = Field::declared(\"x\");
"
    );
    assert_eq!(code(source), expected);
}

#[test]
fn an_entry_too_deep_for_the_depth_types_is_dynamic() {
    let spec = |depth: usize| format!("{}v:int{}", "repeat 1 {".repeat(depth), "}".repeat(depth));
    assert!(code(&spec(8)).contains("pub const v: Field<Int, D8> ="));
    assert!(code(&spec(9)).contains("pub const v: DynField ="));
}

#[test]
fn identifiers_are_unique_and_the_entry_name_stays_whole() {
    let name = "n".repeat(50);
    let source = format!("fn:int a_b:int aB:int {name}a:int {name}b:int");
    let text = code(&source);
    assert!(text.contains("pub const fn_2: Field<Int> = Field::declared(\"fn\");"));
    assert!(text.contains("pub const a_b: Field<Int> = Field::declared(\"a_b\");"));
    assert!(text.contains("pub const a_b_2: Field<Int> = Field::declared(\"aB\");"));
    let short = "n".repeat(40);
    assert!(text.contains(&format!("pub const {short}: Field<Int> =\n")));
    assert!(text.contains(&format!("pub const {short}_2: Field<Int> =\n")));
    assert!(text.contains(&format!("\"{name}a\"")));
    assert!(text.contains(&format!("\"{name}b\"")));
}

#[test]
fn names_of_a_builder_program_stay_as_they_are() {
    let text = code("a:int b:int s:int int:int e1:int");
    for name in ["a", "b", "s", "int", "e1"] {
        assert!(text.contains(&format!("pub const {name}: ")), "{text}");
    }
}

/// Every set of imports long enough to reach the end of a line. Which types a
/// view imports decides where `rustfmt` breaks the `use`.
fn import_specs() -> Vec<String> {
    let mut specs = Vec::new();
    for depths in 0_u32..256 {
        if depths.count_ones() < 6 {
            continue;
        }
        for extras in 0..32 {
            let mut spec = String::new();
            for depth in (0..8).filter(|depth| depths >> depth & 1 == 1) {
                let dimensions = "[1]".repeat(depth + 1);
                spec.push_str(&format!("i{depth}{dimensions}:int\n"));
            }
            for (bit, line) in [
                "f:float\n",
                "s:word\n",
                "n:num\n",
                "if 1 {m:int}\n",
                "d:int d:word\n",
            ]
            .iter()
            .enumerate()
            {
                if extras >> bit & 1 == 1 {
                    spec.push_str(line);
                }
            }
            specs.push(spec);
        }
    }
    specs
}

#[test]
fn imports_are_laid_out_as_rustfmt_does() {
    let directory = Path::new(env!("CARGO_TARGET_TMPDIR")).join("view-imports");
    fs::create_dir_all(&directory).unwrap();
    let mut rustfmt = Command::new("rustfmt");
    rustfmt.args(["--check", "--edition", "2024"]);
    for (index, spec) in import_specs().iter().enumerate() {
        let path = directory.join(format!("view_{index}.rs"));
        fs::write(&path, code(spec)).unwrap();
        rustfmt.arg(path);
    }
    let output = rustfmt.output().unwrap();
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stdout)
    );
}
