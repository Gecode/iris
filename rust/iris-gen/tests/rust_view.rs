//! Which handle each kind of entry gets, and the Rust text of a view.
use gecode_iris_gen::view::{Access, Handle, Leaf, View, view};
use gecode_iris_gen::{Language, view_code};
use gecode_iris_sema::{Analysis, analyze};
use gecode_iris_syntax::{LanguageVersion, parse};
use std::{fs, path::Path, process::Command};

fn analysis(source: &str) -> Analysis {
    let parsed = parse(source.as_bytes(), "test.iris", LanguageVersion::V0_1).unwrap();
    analyze(&parsed)
}

fn code(source: &str) -> String {
    view_code(&analysis(source), Language::Rust).expect("the spec is accepted")
}

/// The access of entry `name` in the view of `source`.
#[track_caller]
fn access(source: &str, name: &str) -> Access {
    let View { handles } = view(&analysis(source)).expect("the spec is accepted");
    let handle = handles.iter().find(|handle| handle.entry == name);
    handle
        .unwrap_or_else(|| panic!("no handle for {name}"))
        .access
}

const fn typed(value: Leaf, depth: usize, optional: bool) -> Access {
    Access::Typed {
        value,
        depth,
        optional,
    }
}

#[test]
fn one_value_type_and_depth_gives_a_typed_handle() {
    for (source, name, expected) in [
        ("x:int", "x", typed(Leaf::Int, 0, false)),
        ("x:float", "x", typed(Leaf::Float, 0, false)),
        ("x:word", "x", typed(Leaf::Str, 0, false)),
        ("x:rest", "x", typed(Leaf::Str, 0, false)),
        ("x:0..9", "x", typed(Leaf::Int, 0, false)),
        ("x:num", "x", typed(Leaf::Num, 0, false)),
        ("x[2][2]:num", "x", typed(Leaf::Num, 2, false)),
        ("list x:word until eol", "x", typed(Leaf::Str, 1, false)),
        ("repeat 2 {x:int}", "x", typed(Leaf::Int, 1, false)),
        ("repeat 2 {let x=1.5}", "x", typed(Leaf::Float, 1, false)),
        ("repeat 0 {if 0 {x:int}}", "x", typed(Leaf::Int, 1, false)),
        ("param p=1", "p", typed(Leaf::Int, 0, false)),
        ("param p=1.5", "p", typed(Leaf::Float, 0, false)),
        ("x:int x:int", "x", typed(Leaf::Int, 0, false)),
        ("if 1 {x:int}", "x", typed(Leaf::Int, 0, true)),
        ("if 1 {x:int} x:int", "x", typed(Leaf::Int, 0, false)),
        (
            "sections {\"{x:int}\" optional}",
            "x",
            typed(Leaf::Int, 0, true),
        ),
        (
            "repeat until \"E\" store _ {x:int}",
            "_",
            typed(Leaf::Str, 0, false),
        ),
    ] {
        assert_eq!(access(source, name), expected, "{source}");
    }
}

#[test]
fn an_open_shape_gives_a_dynamic_handle() {
    for (source, name) in [
        ("x:int x:word", "x"),
        ("x:int x:float", "x"),
        ("x:num x:int", "x"),
        ("x:int x[1]:int", "x"),
        ("x:int repeat 2 {x:int}", "x"),
        ("param p", "p"),
        ("a[1]:int param p=a", "p"),
        ("a[1]:int repeat 2 {let row=a}", "row"),
        ("if 1 {x:int} else {x:word}", "x"),
        ("sections {\"A\" {let y=x} \"B {x:word}\" optional}", "y"),
    ] {
        assert_eq!(access(source, name), Access::Dynamic, "{source}");
    }
}

#[test]
fn an_invalid_spec_reports_the_first_error() {
    let error = view(&analysis("let x=nothing(1)")).unwrap_err();
    assert!(error.message.contains("nothing"), "{error}");
    assert!(view_code(&analysis("let x=nothing(1)"), Language::Rust).is_err());
}

#[test]
fn a_view_lists_entries_by_first_definition() {
    let View { handles } = view(&analysis("b:int a:int b:int")).unwrap();
    let names: Vec<_> = handles.iter().map(|Handle { entry, .. }| entry).collect();
    assert_eq!(names, ["b", "a"]);
}

