//! The TypeScript text of a view. Which handle each entry gets is in
//! `rust_view.rs`; `gecode-iris`'s `typescript_views` test runs oxfmt, oxlint
//! and tsc on the output and reads data through it.
use gecode_iris_gen::{Language, view_code};
use gecode_iris_sema::analyze;
use gecode_iris_syntax::{LanguageVersion, parse};

fn code(source: &str) -> String {
    let parsed = parse(source.as_bytes(), "test.iris", LanguageVersion::V0_1).unwrap();
    view_code(&parsed, &analyze(&parsed), Language::TypeScript).expect("the spec is accepted")
}

const HEADER: &str =
    "// Typed handles of a reader spec, generated by `iris gen --lang typescript`.\n";

/// The declaration of the handle `identifier` of `entry`, with the type
/// arguments of `Handle` as written.
fn declaration(identifier: &str, entry: &str, value: &str, depth: &str, presence: &str) -> String {
    format!(
        "export const {identifier}: Handle<\"{value}\", {depth}, \"{presence}\"> = {{\n  \
         name: \"{entry}\",\n  valueType: \"{value}\",\n  depth: {depth},\n  \
         presence: \"{presence}\",\n}};\n"
    )
}

#[test]
fn a_spec_without_entries_prints_a_module_that_exports_only_the_handle_type() {
    assert_eq!(
        code("skip line\n"),
        format!("{HEADER}\nexport type {{ Handle }} from \"gecode-iris\";\n")
    );
}

#[test]
fn each_handle_type_gives_its_promise() {
    let source = "n:int a[1]:float if n {s:word m[1][1]:num} x:int x:word";
    let expected = [
        format!("{HEADER}\nimport type {{ Handle }} from \"gecode-iris\";\n"),
        declaration("n", "n", "int", "0", "required"),
        declaration("a", "a", "float", "1", "required"),
        declaration("s", "s", "string", "0", "maybe"),
        declaration("m", "m", "num", "2", "maybe"),
        // A builder's dynamic handle may always be absent.
        declaration("x", "x", "dyn", "null", "maybe"),
    ]
    .join("\n");
    assert_eq!(code(source), expected);
}

#[test]
fn an_entry_deeper_than_eight_has_an_open_depth_and_its_value_type() {
    let spec = |depth: usize| format!("{}v:int{}", "repeat 1 {".repeat(depth), "}".repeat(depth));
    assert!(code(&spec(8)).contains(&declaration("v", "v", "int", "8", "required")));
    assert!(code(&spec(9)).contains(&declaration("v", "v", "int", "null", "required")));
}

#[test]
fn identifiers_follow_the_builder_rules_but_avoid_only_what_a_view_must() {
    let name = "n".repeat(30);
    let source = format!(
        "if:int globalThis:int Handle:int then:int int:int b:int e1:int a_b:int _a_b:int name_:int \
         {name}a:int {name}b:int"
    );
    let text = code(&source);
    for (identifier, entry) in [
        ("if2", "if"),
        ("globalThis2", "globalThis"),
        ("Handle2", "Handle"),
        ("then2", "then"),
        ("int", "int"),
        ("b", "b"),
        ("e1", "e1"),
        ("a_b", "a_b"),
        ("a_b2", "_a_b"),
        ("name", "name_"),
        (&"n".repeat(24), &format!("{name}a")),
        (&format!("{}2", "n".repeat(24)), &format!("{name}b")),
    ] {
        let expected = declaration(identifier, entry, "int", "0", "required");
        assert!(text.contains(&expected), "{expected}in\n{text}");
    }
    let stored = code("repeat until \"E\" store _ {}");
    assert!(stored.contains(&declaration("_", "_", "string", "0", "required")));
}

/// The widest head, `export const IDENTIFIER: Handle<"string", null,
/// "required"> = {` with the widest identifier and a suffix, fits within
/// oxfmt's line, so oxfmt never breaks it.
#[test]
fn the_widest_head_fits_on_a_line() {
    let name = "n".repeat(40);
    let deep = |entry: &str| format!("{}{entry}:word{}", "repeat 1 {".repeat(9), "}".repeat(9));
    let text = code(&format!("{name}x:int {}", deep(&format!("{name}y"))));
    assert!(
        text.contains("Handle<\"string\", null, \"required\">"),
        "{text}"
    );
    let widest = text
        .lines()
        .filter(|line| line.starts_with("export const "))
        .map(str::len)
        .max()
        .unwrap();
    assert!(
        text.contains(&format!("export const {}2:", "n".repeat(24))),
        "{text}"
    );
    assert!(widest <= 100, "{widest}: {text}");
}
