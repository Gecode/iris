import { spawnSync } from 'node:child_process';
import { readFile, writeFile, mkdir, rename } from 'node:fs/promises';
import { resolve } from 'node:path';
import { gzipSync } from 'node:zlib';
import { repository, siteDirectory } from './format-sources.mjs';

const generated = resolve(siteDirectory, 'src/generated');
await mkdir(generated, { recursive: true });
if (process.argv.includes('--disabled')) {
  await writeFile(resolve(generated, 'playground-wasm.ts'), `// Documentation-only development; never accepted by check:wasm.\nexport async function initialize(): Promise<void> { throw new Error('The WASM toolchain is disabled. Use the CLI or format library, or restart with npm run dev.'); }\nexport function read(_request: string): string { throw new Error('Reader unavailable'); }\nexport const check = read;\nexport const format = read;\n`);
} else {
  const manifest = await readFile(resolve(repository, 'rust/iris-wasm/Cargo.toml'), 'utf8');
  const version = manifest.match(/wasm-bindgen = "=([\d.]+)"/)?.[1];
  if (!version) throw new Error('iris-wasm must pin wasm-bindgen exactly');
  let actual;
  try { actual = run('wasm-bindgen', ['--version']).trim(); }
  catch { throw new Error(`Install the binding CLI: cargo install wasm-bindgen-cli --locked --version ${version}`); }
  if (actual !== `wasm-bindgen ${version}`) throw new Error(`Expected wasm-bindgen ${version}; install with cargo install wasm-bindgen-cli --locked --version ${version}`);
  const targets = run('rustup', ['target', 'list', '--installed']);
  if (!targets.split('\n').includes('wasm32-unknown-unknown')) throw new Error('Install the target: rustup target add wasm32-unknown-unknown');
  const env = { ...process.env };
  const memoryFlag = '-C\x1flink-arg=--max-memory=268435456';
  env.CARGO_ENCODED_RUSTFLAGS = env.CARGO_ENCODED_RUSTFLAGS
    ? `${env.CARGO_ENCODED_RUSTFLAGS}\x1f${memoryFlag}`
    : [env.RUSTFLAGS ?? '', '-C link-arg=--max-memory=268435456'].join(' ').trim().split(/\s+/).join('\x1f');
  delete env.RUSTFLAGS;
  const build = run('cargo', ['build', '--locked', '-p', 'iris-wasm', '--lib', '--target', 'wasm32-unknown-unknown', '--profile', 'wasm', '--message-format=json'], { cwd: resolve(repository, 'rust'), env });
  const artifact = build.trim().split('\n').map(line => JSON.parse(line)).find(item => item.reason === 'compiler-artifact' && item.target.name === 'iris_wasm')?.filenames.find(path => path.endsWith('.wasm'));
  if (!artifact) throw new Error('Cargo did not report iris_wasm.wasm');
  const output = resolve(generated, 'wasm');
  await mkdir(output, { recursive: true });
  run('wasm-bindgen', [artifact, '--target', 'web', '--out-dir', output, '--out-name', 'iris_wasm']);
  const binary = resolve(output, 'iris_wasm_bg.wasm');
  run(process.execPath, [resolve(siteDirectory, 'node_modules/binaryen/bin/wasm-opt'), binary, '-Oz', '--enable-bulk-memory', '--enable-nontrapping-float-to-int', '--enable-sign-ext', '-o', `${binary}.optimized`]);
  const bytes = await readFile(`${binary}.optimized`);
  if (!WebAssembly.validate(bytes)) throw new Error('Optimized WASM failed validation');
  const gzip = gzipSync(bytes, { level: 9 }).length;
  console.log(`WASM optimized: ${bytes.length} bytes raw / ${gzip} bytes gzip (limits 1048576 / 393216).`);
  if (bytes.length > 1048576 || gzip > 393216) throw new Error('WASM size budget exceeded');
  await rename(`${binary}.optimized`, binary);
  await writeFile(resolve(generated, 'playground-wasm.ts'), `// Generated by scripts/build-wasm.mjs.\nimport init from './wasm/iris_wasm.js';\nimport wasmUrl from './wasm/iris_wasm_bg.wasm?url';\nexport { read, check, format } from './wasm/iris_wasm.js';\nexport async function initialize(): Promise<void> { await init({ module_or_path: wasmUrl }); }\n`);
  console.log(`WASM glue: ${(await readFile(resolve(output, 'iris_wasm.js'))).length} bytes.`);
}
function run(command, args, options = {}) {
  const result = spawnSync(command, args, { encoding: 'utf8', maxBuffer: 16 << 20, stdio: ['pipe', 'pipe', 'inherit'], ...options });
  if (result.error || result.status !== 0) throw new Error(`${command} failed. ${result.error ?? ''}`);
  return result.stdout;
}
