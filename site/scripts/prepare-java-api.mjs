import { spawnSync } from 'node:child_process';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { parse, serialize } from 'parse5';
import { parse as parseToml } from 'smol-toml';
import { repository, siteDirectory } from './format-sources.mjs';

// Runs Javadoc over dev.gecode:iris and Dokka over dev.gecode:iris-kotlin, and
// keeps the content of their pages for the site's own shell. As for C++, the
// tools' own pages would bring their navigation, scripts and styles, and they
// do not pass the site's link, HTML and contrast checks.
const javaPath = '/using/java/api/';
const kotlinPath = '/using/java/kotlin-api/';
const keptAttributes = new Set(['class', 'href', 'id']);
const java = resolve(repository, 'java');
const javadocPages = resolve(java, 'iris/build/docs/javadoc/dev.gecode.iris/dev/gecode/iris');
const dokkaPages = resolve(java, 'iris-kotlin/build/dokka/html/iris-kotlin/dev.gecode.iris.kotlin');

runGradle([':iris:javadoc', ':iris-kotlin:dokkaGenerate']);
const javaFiles = (await readdir(javadocPages)).filter(file => javaSlug(file) !== undefined).sort();
const kotlinFiles = (await readdir(dokkaPages)).filter(file => file.endsWith('.html')).sort();
const sources = await Promise.all(javaFiles.map(file => readFile(resolve(javadocPages, file), 'utf8')));
const reference = {
  java: {
    javadoc: /<!-- Generated by javadoc \((\d+)\) -->/.exec(sources[0])[1],
    pages: javaFiles.map((file, index) => extractJavadocPage(file, sources[index], javaFiles)),
  },
  kotlin: {
    dokka: parseToml(await readFile(resolve(java, 'gradle/libs.versions.toml'), 'utf8')).versions.dokka,
    pages: await Promise.all(kotlinFiles.map(async file => extractDokkaPage(file, await readFile(resolve(dokkaPages, file), 'utf8'), kotlinFiles, javaFiles))),
  },
};
await mkdir(resolve(siteDirectory, 'src/generated'), { recursive: true });
await writeFile(resolve(siteDirectory, 'src/generated/java-api.json'), JSON.stringify(reference.java));
await writeFile(resolve(siteDirectory, 'src/generated/kotlin-api.json'), JSON.stringify(reference.kotlin));
console.log(`Prepared ${javaFiles.length} pages with Javadoc ${reference.java.javadoc} and ${kotlinFiles.length} with Dokka ${reference.kotlin.dokka}.`);

function runGradle(tasks) {
  const result = spawnSync('./gradlew', ['--console=plain', ...tasks], { cwd: java, stdio: ['ignore', 'inherit', 'inherit'] });
  if (result.error || result.status !== 0) throw new Error(`The Java API reference needs Java 27: ./gradlew ${tasks.join(' ')} failed. ${result.error ?? ''}`);
}

// The URL below the reference of a page to publish, such as value-int-value for
// Value.IntValue.html; other pages are indexes that the site's navigation replaces.
function javaSlug(file) {
  if (file === 'package-summary.html') return '';
  if (!/^[A-Z][\w.]*\.html$/.test(file)) return undefined;
  return file.replace(/\.html$/, '').replaceAll('.', '-').replace(/(?<=[a-z])(?=[A-Z])/g, '-').toLowerCase();
}

function kotlinSlug(file) { return file === 'index.html' ? '' : file.replace(/\.html$/, ''); }

function pageUrl(root, slug) { return `${root}${slug === '' ? '' : `${slug}/`}`; }

function extractJavadocPage(file, source, published) {
  const document = parse(source);
  const contents = find(document, node => node.tagName === 'main');
  const title = text(find(contents, node => hasClass(node, 'title'))).trim();
  for (const node of descendants(contents).filter(node => hasClass(node, 'header') || hasClass(node, 'table-tabs') || node.tagName === 'hr')) detach(node);
  for (const link of descendants(contents).filter(node => attribute(node, 'href')?.includes('serialized-form.html'))) dropNote(link);
  for (const node of descendants(contents)) {
    const id = attribute(node, 'id');
    if (id) setAttribute(node, 'id', javadocFragment(id));
    // A section holds the target of a member, and the outline links its heading.
    if (node.tagName === 'section' && id) moveIdToHeading(node);
    if (node.tagName === 'a' && attribute(node, 'href')) setAttribute(node, 'href', javaHref(attribute(node, 'href'), file, published));
  }
  clean(contents);
  return { slug: javaSlug(file), title, headings: javadocOutline(document), html: serialize(contents) };
}

// Javadoc's table of contents names overloads apart, which the headings do not.
function javadocOutline(document) {
  const toc = descendants(document).find(node => hasClass(node, 'toc-list'));
  if (!toc) return [];
  return descendants(toc).filter(node => node.tagName === 'a' && attribute(node, 'href') !== '#').map(link => ({
    depth: ancestors(link).filter(node => hasClass(node, 'toc-list')).length + 1,
    slug: javadocFragment(decodeURIComponent(attribute(link, 'href').slice(1))),
    text: text(link).trim(),
  }));
}

// A member's id is its signature, such as read(byte[],java.lang.String).
function javadocFragment(id) {
  return id.replace(/[^\w-]+/g, '-').replace(/-+$/, '');
}

function moveIdToHeading(section) {
  const heading = section.childNodes.find(node => ['h2', 'h3'].includes(node.tagName));
  if (!heading) return;
  setAttribute(heading, 'id', attribute(section, 'id'));
  section.attrs = section.attrs.filter(({ name }) => name !== 'id');
}

// The serialized form of an exception or record is no part of the reference.
function dropNote(link) {
  const description = ancestors(link).find(node => node.tagName === 'dd');
  const notes = description.parentNode;
  const elements = notes.childNodes.filter(node => node.tagName);
  detach(elements[elements.indexOf(description) - 1]);
  detach(description);
  if (!notes.childNodes.some(node => node.tagName)) detach(notes);
}

function javaHref(href, file, published) {
  if (/^[a-z]+:/.test(href)) return href;
  const [target, fragment] = decodeURIComponent(href).split('#');
  const anchor = fragment ? `#${javadocFragment(fragment)}` : '';
  if (target === '') return anchor;
  if (!published.includes(target)) throw new Error(`${file}: link to the unpublished ${href}`);
  return `${pageUrl(javaPath, javaSlug(target))}${anchor}`;
}

function extractDokkaPage(file, source, published, javaPublished) {
  const contents = find(parse(source), node => attribute(node, 'id') === 'content');
  const heading = text(find(contents, node => node.tagName === 'h1')).trim().replace(/\s+/g, ' ');
  const title = file === 'index.html' ? 'Package dev.gecode.iris.kotlin' : heading;
  const dropped = node => ['breadcrumbs', 'cover', 'footer', 'tabs-section', 'anchor-wrapper'].some(name => hasClass(node, name)) || (node.tagName === 'a' && attribute(node, 'href') === undefined);
  for (const node of descendants(contents).filter(dropped)) detach(node);
  const headings = [];
  for (const node of descendants(contents)) {
    if (attribute(node, 'data-unresolved-link')) linkJavaType(node, file, javaPublished);
    else if (node.tagName === 'a') setAttribute(node, 'href', kotlinHref(attribute(node, 'href'), file, published));
    // Dokka puts blocks in spans, and starts a function's sections at h4.
    if (node.tagName === 'span' && descendants(node).some(child => child.tagName === 'div')) rename(node, 'div');
    if (hasClass(node, 'tableheader')) {
      rename(node, 'h2');
      const name = text(node).trim();
      const slug = name.toLowerCase().replace(/\W+/g, '-');
      setAttribute(node, 'id', slug);
      headings.push({ depth: 2, slug, text: name });
    }
  }
  clean(contents);
  return { slug: kotlinSlug(file), title, headings, html: serialize(contents) };
}

// Dokka cannot resolve a type of dev.gecode:iris, and marks it with its
// package and class, such as dev.gecode.iris/Value/get/#kotlin.Int/....
function linkJavaType(node, file, javaPublished) {
  const [, type] = attribute(node, 'data-unresolved-link').split('/');
  const target = `${type}.html`;
  if (!javaPublished.includes(target)) throw new Error(`${file}: link to the unknown Java type ${type}`);
  rename(node, 'a');
  setAttribute(node, 'href', pageUrl(javaPath, javaSlug(target)));
}

function kotlinHref(href, file, published) {
  if (/^[a-z]+:/.test(href)) return href;
  const [target, fragment] = href.split('#');
  if (!published.includes(target)) throw new Error(`${file}: link to the unpublished ${href}`);
  return `${pageUrl(kotlinPath, kotlinSlug(target))}${fragment === undefined ? '' : `#${fragment}`}`;
}

function clean(contents) {
  for (const node of descendants(contents)) {
    if (node.nodeName === '#comment') detach(node);
    node.attrs = node.attrs?.filter(({ name }) => keptAttributes.has(name));
  }
}

function find(root, test) {
  const node = descendants(root).find(test);
  if (!node) throw new Error('Generated page without the expected structure');
  return node;
}
function descendants(node) { return (node.childNodes ?? []).flatMap(child => [child, ...descendants(child)]); }
function ancestors(node) { return node.parentNode ? [node.parentNode, ...ancestors(node.parentNode)] : []; }
function text(node) { return node.nodeName === '#text' ? node.value : (node.childNodes ?? []).map(text).join(''); }
function attribute(node, name) { return node.attrs?.find(attr => attr.name === name)?.value; }
function hasClass(node, name) { return (attribute(node, 'class') ?? '').split(/\s+/).includes(name); }
function detach(node) { node.parentNode.childNodes.splice(node.parentNode.childNodes.indexOf(node), 1); }
function rename(node, tagName) { node.tagName = node.nodeName = tagName; }
function setAttribute(node, name, value) {
  node.attrs = [...node.attrs.filter(attr => attr.name !== name), { name, value }];
}
